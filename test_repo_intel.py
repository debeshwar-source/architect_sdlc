def test_git_uses_the_users_own_config(monkeypatch):
    """A plain `git clone` sees system/global config (credential helpers); we must not hide it."""
    seen = {}

    class R:
        returncode, stdout, stderr = 0, "", ""
    monkeypatch.setattr(ingest.subprocess, "run", lambda *a, **k: seen.update(env=k["env"]) or R())
    ingest.git(["status"])
    assert "GIT_CONFIG_NOSYSTEM" not in seen["env"] and "GIT_CONFIG_GLOBAL" not in seen["env"]
    assert seen["env"]["GIT_TERMINAL_PROMPT"] == "0"


